def compute_rs_ratings(ohlcv, bench_close):
    """Compute relative strength percentile rankings vs benchmark."""
    raw = {}
    for tk, df in ohlcv.items():
        c = df["Close"]
        if len(c) < P.RS_LOOKBACK_SHORT: continue
        common = c.index.intersection(bench_close.index)
        if len(common) < P.RS_LOOKBACK_SHORT: continue
        stock = c.reindex(common); b = bench_close.reindex(common)

        if len(stock) >= P.RS_LOOKBACK_LONG and len(b) >= P.RS_LOOKBACK_LONG:
            sl = float(stock.iloc[-1]/stock.iloc[-P.RS_LOOKBACK_LONG])
            bl = float(b.iloc[-1]/b.iloc[-P.RS_LOOKBACK_LONG])
            rs_long = (sl/bl - 1)*100 if bl > 0 else 0
        else:
            rs_long = 0

        if len(stock) >= P.RS_LOOKBACK_SHORT:
            ss = float(stock.iloc[-1]/stock.iloc[-P.RS_LOOKBACK_SHORT])
            bs = float(b.iloc[-1]/b.iloc[-P.RS_LOOKBACK_SHORT])
            rs_short = (ss/bs - 1)*100 if bs > 0 else 0
        else:
            rs_short = 0

        raw[tk] = P.RS_SHORT_WEIGHT*rs_short + P.RS_LONG_WEIGHT*rs_long
    if not raw: return {}
    vals = sorted(raw.values()); n = len(vals)
    return {tk: round(np.searchsorted(vals, v, side='right')/n*100, 1)
            for tk, v in raw.items()}


def gate1_momentum(df, rs_rating):
    """Hard gate: RS ≥ 70th percentile + price > 50 DMA."""
    if len(df) < P.MIN_HISTORY_DAYS:
        return {"pass": False, "reason": "history"}
    if rs_rating < P.RS_MIN_PERCENTILE:
        return {"pass": False, "reason": f"rs={rs_rating:.0f}<{P.RS_MIN_PERCENTILE}"}
    c = df["Close"]; last = float(c.iloc[-1])
    ma50 = sma(c, 50)
    if P.REQUIRE_ABOVE_MA50 and not pd.isna(ma50.iloc[-1]) and last <= float(ma50.iloc[-1]):
        return {"pass": False, "reason": "below_ma50"}
    return {"pass": True, "rs_rating": rs_rating}


