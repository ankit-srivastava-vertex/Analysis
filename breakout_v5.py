def detect_resistance(df):
    """Detect horizontal resistance via fractal pivot clustering."""
    if len(df) < P.BASE_MIN_DAYS + 20: return None
    last_close = float(df["Close"].iloc[-1])
    window = df.tail(min(300, len(df)))

    piv_t = fractal_pivots(window["High"], P.FRACTAL_K_TIGHT)
    piv_b = fractal_pivots(window["High"], P.FRACTAL_K_BROAD)
    pivots = pd.concat([window["High"][piv_t], window["High"][piv_b]]).groupby(level=0).max()
    if len(pivots) < P.MIN_TOUCHES: return None

    levels = sorted(pivots.tolist(), reverse=True)
    clusters = []
    for lvl in levels:
        placed = False
        for c in clusters:
            if abs(lvl - c["level"])/c["level"] <= P.RES_BAND_PCT:
                c["sum"] += lvl; c["count"] += 1
                c["level"] = c["sum"]/c["count"]; placed = True; break
        if not placed:
            clusters.append({"level": lvl, "sum": lvl, "count": 1})

    candidates = []
    for cl in clusters:
        R = cl["level"]
        if R <= 0: continue
        dist = (R - last_close)/last_close
        if cl["count"] < P.MIN_TOUCHES: continue
        if dist < P.PROXIMITY_MIN or dist > P.PROXIMITY_MAX: continue
        touch_dates = [ts for ts in pivots.index
                       if abs(pivots.loc[ts] - R)/R <= P.RES_BAND_PCT]
        if len(touch_dates) < P.MIN_TOUCHES: continue
        base_start = min(touch_dates)
        base_len = (df.index[-1] - base_start).days
        if base_len < P.BASE_MIN_DAYS: continue
        if base_len > P.BASE_MAX_DAYS:
            recent = [t for t in touch_dates if (df.index[-1]-t).days <= P.BASE_MAX_DAYS]
            if len(recent) < P.MIN_TOUCHES: continue
            base_start = min(recent); base_len = (df.index[-1]-base_start).days
        candidates.append({"R": R, "touches": len(touch_dates), "base_start": base_start,
                           "base_len_days": base_len, "distance_pct": dist})
    if not candidates: return None
    candidates.sort(key=lambda c: (-c["touches"], abs(c["distance_pct"])))
    best = candidates[0]
    higher = [c for c in candidates if c["R"] > best["R"]*1.02
              and c["touches"] >= max(2, int(best["touches"]*0.7))]
    if higher:
        higher.sort(key=lambda c: -c["R"]); return higher[0]
    return best


def gate5_technical(df):
    """Hard gate: resistance with flat ceiling, 2+ touches, proximity check."""
    res = detect_resistance(df)
    if res is None: return {"pass": False, "reason": "no_resistance", "R": None}
    R = res["R"]; base = df.loc[res["base_start"]:]
    if base.empty: return {"pass": False, "reason": "empty_base", "R": R}

    bh = float(base["High"].max()); bl = float(base["Low"].min())
    br = (bh - bl)/R if R > 0 else 1.0
    if br > P.BASE_MAX_RANGE:
        return {"pass": False, "reason": "base_wide", "R": R}

    seg = df.tail(P.FAILED_BO_LOOKBACK)
    if not seg.empty and bool((seg["High"] > R*1.03).any()) and float(df["Close"].iloc[-1]) < R*0.98:
        return {"pass": False, "reason": "failed_bo", "R": R}

    # FLAT CEILING CHECK: the highs across the base must be at roughly the
    # same level — a genuine horizontal ceiling, not trending highs.
    bh = base["High"].values
    nb = len(bh); t = max(1, nb // 3)
    if nb >= 9:
        h1, h2, h3 = bh[:t].max(), bh[t:2*t].max(), bh[2*t:].max()
        mx = max(h1, h2, h3)
        if any(abs(x - mx)/mx > 0.035 for x in [h1, h2, h3]):
            return {"pass": False, "reason": "ceiling_not_flat", "R": R}

    lows_idx = base["Low"].rolling(11, center=True).min() == base["Low"]
    swing_lows = base["Low"][lows_idx].dropna()
    higher_lows = (linreg_slope(swing_lows) > 0) if len(swing_lows) >= P.HIGHER_LOWS_MIN_SWINGS else False

    v50 = float(df["Volume"].rolling(50).mean().iloc[-1]) if len(df) >= 50 else 1
    v10 = float(df["Volume"].tail(10).mean())
    vdu = (1.0 - v10/v50) if v50 > 0 else 0

    # VCP contractions
    n_vcp = 0
    if len(base) >= 30:
        h = base["High"].values; l = base["Low"].values; n = len(h); k = 5
        pivs = [(i, float(h[i])) for i in range(k, n-k) if h[i] == h[max(0,i-k):i+k+1].max()]
        pbs = []
        for j in range(1, len(pivs)):
            ip, pp = pivs[j-1]; ic, _ = pivs[j]
            sl = float(l[ip:ic+1].min())
            if pp > 0: pbs.append((pp-sl)/pp)
        for j in range(1, len(pbs)):
            if pbs[j] < pbs[j-1]*0.85 and pbs[j] < 0.15: n_vcp += 1

    return {"pass": True, "R": R, "distance_pct": res["distance_pct"],
            "touches": res["touches"], "base_start": res["base_start"],
            "base_days": res["base_len_days"], "base_range": round(br*100, 1),
            "higher_lows": higher_lows, "vdu": round(vdu, 3), "n_vcp": n_vcp}


