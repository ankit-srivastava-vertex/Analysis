def _load_patches():
    """Auto-load LLM-generated patch_filter functions from Output/breakout_patches/.
    Each patch file must define a patch_filter(pick, df) -> bool function.
    """
    global _loaded_patches
    if _loaded_patches or not os.path.isdir(PATCH_DIR):
        return
    import importlib.util
    for fname in sorted(os.listdir(PATCH_DIR)):
        if not fname.startswith("patch_") or not fname.endswith(".py"):
            continue
        fpath = os.path.join(PATCH_DIR, fname)
        try:
            spec = importlib.util.spec_from_file_location(
                fname.replace(".py", ""), fpath)
            mod = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(mod)
            if hasattr(mod, "patch_filter") and callable(mod.patch_filter):
                _loaded_patches.append(mod.patch_filter)
        except Exception:
            continue
    if _loaded_patches:
        print(f"  Loaded {len(_loaded_patches)} LLM code patches")


