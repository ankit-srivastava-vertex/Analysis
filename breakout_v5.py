def gate3_institutional(df):
    """Any one signal = pass. Four independent signals checked."""
    signals = []
    if len(df) < 30: return {"pass": False, "signals": [], "reason": "short"}

    # Signal 1: OBV divergence
    if len(df) >= P.OBV_LONG_WINDOW:
        o = obv(df)
        obv_rh = float(o.tail(P.OBV_SHORT_WINDOW).max())
        obv_ph = float(o.iloc[-P.OBV_LONG_WINDOW:-P.OBV_SHORT_WINDOW].max())
        prh = float(df["High"].tail(P.OBV_SHORT_WINDOW).max())
        pph = float(df["High"].iloc[-P.OBV_LONG_WINDOW:-P.OBV_SHORT_WINDOW].max())
        if obv_rh > obv_ph and prh < pph * 1.01:
            signals.append("obv_divergence")

    # Signal 2: Volume accumulation (OBV rising, total vol declining)
    if len(df) >= 30:
        o = obv(df)
        if linreg_slope(o.tail(20)) > 0 and linreg_slope(df["Volume"].tail(20)) < 0:
            signals.append("vol_accumulation")

    # Signal 3: Up-day volume dominance
    if len(df) >= 20:
        r = df.tail(20)
        up = r[r["Close"] > r["Close"].shift(1)]
        dn = r[r["Close"] < r["Close"].shift(1)]
        if len(up) > 0 and len(dn) > 0:
            if float(up["Volume"].mean()) > float(dn["Volume"].mean()) * 1.15:
                signals.append("up_vol_dominant")

    # Signal 4: Recent volume surge on up-close days
    if len(df) >= 10:
        last5 = df.tail(5)
        up_days = last5[last5["Close"] > last5["Open"]]
        if len(up_days) >= 3:
            avg_up_vol = float(up_days["Volume"].mean())
            avg_50_vol = float(df["Volume"].tail(50).mean()) if len(df) >= 50 else float(df["Volume"].mean())
            if avg_up_vol > avg_50_vol * 1.3:
                signals.append("recent_vol_surge")

    return {"pass": len(signals) > 0, "signals": signals,
            "reason": ",".join(signals) if signals else "no_signal"}


