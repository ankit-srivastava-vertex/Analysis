def run_scan(ohlcv, bench_df, rs_ratings, verbose=False, use_llm=True):
    """Run the scan. Returns (picks, funnel_stats).

    Auto-loads LLM-generated code patches from Output/breakout_patches/
    and applies them as additional filters after scoring. When use_llm is
    True, also runs market regime assessment and conviction court.
    """
    _load_patches()

    funnel = defaultdict(int)
    funnel["total_universe"] = len(ohlcv)
    picks = []

    regime = None
    effective_min_score = P.MIN_SCORE
    effective_prox_max = P.PROXIMITY_MAX
    if use_llm and _USE_LLM:
        regime = llm_market_regime(bench_df)
        if regime:
            if (regime.get("regime") == "hostile"
                    and regime.get("breakout_receptiveness", 100) < 30):
                print("  [regime] HOSTILE market — scanning skipped")
                funnel["regime_skip"] = 1
                return [], dict(funnel)
            adj = regime.get("dynamic_adjustments", {})
            if "min_score_override" in adj:
                effective_min_score = max(P.MIN_SCORE, int(adj["min_score_override"]))
            if "proximity_max_override" in adj:
                effective_prox_max = min(P.PROXIMITY_MAX, float(adj["proximity_max_override"]))

    b0_score, b0_detail = booster_market_regime(bench_df)
    market_ok = b0_score > P.W_MARKET * 0.5
    if verbose:
        status = "✅ FAVORABLE" if market_ok else "⚠️ WEAK (score reduced)"
        print(f"  Market: {status} — boost={b0_score}/{P.W_MARKET}, {b0_detail}")

    for tk, df in ohlcv.items():
        funnel["processed"] += 1

        # Pre-filters
        if len(df) < P.MIN_HISTORY_DAYS:
            funnel["drop_history"] += 1; continue
        last_close = float(df["Close"].iloc[-1])
        if last_close < P.MIN_PRICE:
            funnel["drop_price"] += 1; continue
        avg_vol = float(df["Volume"].tail(50).mean())
        if avg_vol < P.MIN_AVG_VOLUME:
            funnel["drop_volume"] += 1; continue
        # Turnover check (volume × price)
        avg_turnover = avg_vol * last_close
        if avg_turnover < P.MIN_AVG_TURNOVER:
            funnel["drop_turnover"] += 1; continue

        # HARD GATE 1: Momentum
        rs = rs_ratings.get(tk, 0)
        g1 = gate1_momentum(df, rs)
        if not g1["pass"]:
            funnel["g1_fail"] += 1; continue
        funnel["g1_pass"] += 1

        # HARD GATE 3: Institutional
        g3 = gate3_institutional(df)
        if not g3["pass"]:
            funnel["g3_fail"] += 1; continue
        funnel["g3_pass"] += 1

        # HARD GATE 5: Technical Setup
        g5 = gate5_technical(df)
        if not g5["pass"]:
            funnel["g5_fail"] += 1; continue
        funnel["g5_pass"] += 1

        # SCORE BOOSTERS (not gates)
        b4_score, b4_types = booster_squeeze(df)
        b6_score, b6_detail = booster_weekly(df, g5["R"])

        score = compute_score(rs, g3, g5, b0_score, b4_score, b6_score)
        if score < effective_min_score:
            funnel["low_score"] += 1; continue

        rp = risk_plan(df, g5["R"], g5["base_start"])

        # R:R enforcement — reject picks with poor risk/reward
        if rp.get("rr", 0) < 1.0:
            funnel["rr_too_low"] += 1; continue

        # Apply LLM-generated patch filters (now with real R:R)
        pick_preview = {"ticker": tk, "score": score, "close": round(last_close, 2),
                        "resistance": round(g5["R"], 2),
                        "distance_pct": round(g5["distance_pct"]*100, 2),
                        "touches": g5["touches"], "base_days": g5["base_days"],
                        "squeeze_type": ",".join(b4_types),
                        "institutional": ",".join(g3.get("signals", [])),
                        "rr": rp.get("rr", 0)}
        patch_rejected = False
        for pf in _loaded_patches:
            try:
                if not pf(pick_preview, df):
                    funnel["patch_filter"] += 1
                    patch_rejected = True
                    break
            except Exception:
                pass
        if patch_rejected:
            continue

        funnel["recommended"] += 1

        picks.append({
            "ticker": tk,
            "score": score,
            "close": round(last_close, 2),
            "resistance": round(g5["R"], 2),
            "distance_pct": round(g5["distance_pct"]*100, 2),
            "rs_rating": rs,
            "touches": g5["touches"],
            "base_days": g5["base_days"],
            "base_range": g5["base_range"],
            "higher_lows": g5["higher_lows"],
            "n_vcp": g5["n_vcp"],
            "squeeze_type": ",".join(b4_types),
            "institutional": ",".join(g3.get("signals", [])),
            "weekly_rsi": b6_detail.get("weekly_rsi", 0),
            "market_boost": b0_score,
            "squeeze_boost": b4_score,
            "weekly_boost": b6_score,
            **rp,
        })

    picks.sort(key=lambda x: -x["score"])

    # LLM conviction court — final qualitative filter
    if use_llm and _USE_LLM and picks:
        pre_court = len(picks)
        picks = llm_conviction_court(picks, ohlcv, regime)
        if len(picks) < pre_court:
            funnel["llm_court_rejected"] = pre_court - len(picks)
        # Re-sort by LLM conviction (if available) then score
        picks.sort(key=lambda x: (-x.get("llm_conviction", x["score"]), -x["score"]))

    picks = picks[:P.MAX_PICKS]
    return picks, dict(funnel)


