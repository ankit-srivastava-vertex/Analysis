# ═══════════════════════════════════════════════════════════════════════════════

def compute_score(rs_rating, g3, g5, b0_score, b4_score, b6_score):
    """Composite 0-100 conviction score."""
    # Core (from hard gates): RS + proximity + base quality + institutional
    s_rs = P.W_RS * min(rs_rating/100, 1.0)

    dist = abs(g5.get("distance_pct", 0.05))
    s_prox = P.W_PROXIMITY * max(0, 1.0 - dist/0.04)

    touches = g5.get("touches", 0)
    hl = 1.0 if g5.get("higher_lows") else 0.5
    vcp = min(g5.get("n_vcp", 0)/2, 0.5)
    s_base = P.W_BASE * min(touches/4*0.5 + hl*0.3 + vcp + 0.2, 1.0)

    n_sig = len(g3.get("signals", []))
    s_inst = P.W_INST * min(n_sig/3, 1.0)

    total = s_rs + s_prox + s_base + s_inst + b0_score + b4_score + b6_score
    return round(total, 1)


def risk_plan(df, R, base_start):
    """Compute entry, stop, target, and risk:reward for a breakout pick."""
    last = float(df["Close"].iloc[-1])
    base = df.loc[base_start:]
    bl = float(base["Low"].min()) if not base.empty else last*0.9
    sl = float(base["Low"].tail(20).min()) if len(base) >= 20 else bl
    stop = sl * 0.99
    height = R - bl
    target = R + height
    risk = last - stop
    reward = target - last
    rr = round(reward/risk, 2) if risk > 0 else 0
    return {"entry": round(last, 2), "stop": round(stop, 2), "target": round(target, 2),
            "risk_pct": round(risk/last*100, 2) if last else 0,
            "reward_pct": round(reward/last*100, 2) if last else 0, "rr": rr}


