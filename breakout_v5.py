def write_excel(picks, funnel, out_path=None):
    """Write scan results and funnel stats to Excel."""
    if out_path is None: out_path = os.path.join(SCRIPT_DIR, "breakout_v5_watchlist.xlsx")
    with pd.ExcelWriter(out_path, engine="openpyxl") as w:
        if picks:
            df = pd.DataFrame(picks)
            cols = ["ticker", "score", "close", "resistance", "distance_pct",
                    "rs_rating", "touches", "base_days", "base_range",
                    "higher_lows", "n_vcp", "squeeze_type", "institutional",
                    "weekly_rsi", "market_boost", "squeeze_boost", "weekly_boost",
                    "entry", "stop", "target", "risk_pct", "reward_pct", "rr"]
            df[[c for c in cols if c in df.columns]].to_excel(
                w, sheet_name="Breakout Candidates", index=False)
        else:
            pd.DataFrame({"Note": ["No stocks recommended"]}).to_excel(
                w, sheet_name="Breakout Candidates", index=False)
        pd.DataFrame([{"Gate": k, "Count": v} for k, v in sorted(funnel.items())]).to_excel(
            w, sheet_name="Funnel", index=False)
    print(f"\n  📊 Excel: {out_path}")


def write_backtest_excel(results, out_path=None):
    """Write backtest results to Excel with summary and all picks."""
    if out_path is None: out_path = os.path.join(SCRIPT_DIR, "breakout_v5_backtest.xlsx")
    with pd.ExcelWriter(out_path, engine="openpyxl") as w:
        summary = {"Metric": ["Total Picks", "Breakouts", "Success Rate", "Avg Weekly SR",
                               "Avg Picks/Week", "Avg Max Gain", "Avg Max DD"],
                   "Value": [results['total_picks'], results['total_success'],
                             f"{results['overall_success_rate']:.1f}%",
                             f"{results['avg_weekly_success_rate']:.1f}%",
                             results['avg_picks_per_week'],
                             f"{results['avg_max_gain_pct']:.2f}%",
                             f"{results['avg_max_drawdown_pct']:.2f}%"]}
        pd.DataFrame(summary).to_excel(w, sheet_name="Summary", index=False)
        ap = results.get("all_picks", [])
        if ap:
            df = pd.DataFrame(ap)
            cols = ["test_date", "ticker", "score", "close", "resistance",
                    "distance_pct", "rs_rating", "success", "max_gain_pct",
                    "max_drawdown_pct", "days_to_breakout"]
            df[[c for c in cols if c in df.columns]].to_excel(w, sheet_name="All Picks", index=False)
    print(f"\n  📊 Backtest Excel: {out_path}")


