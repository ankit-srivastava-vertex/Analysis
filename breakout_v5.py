    print(f"  Avg picks/week:        {r['avg_picks_per_week']:.1f}")
    print(f"  Avg max gain:          {r['avg_max_gain_pct']:.2f}%")
    print(f"  Avg max drawdown:      {r['avg_max_drawdown_pct']:.2f}%")
    print("="*70)

    failed = [p for p in r.get("all_picks", []) if not p.get("success")]
    if failed:
        print(f"\n  Failed picks ({len(failed)}):")
        for p in failed[:20]:
            print(f"    {p['test_date']} {p['ticker']}: R={p['resistance']}, "
                  f"gain={p['max_gain_pct']:.1f}%, dd={p['max_drawdown_pct']:.1f}%")

    # Worst weeks
    bad = [w for w in r.get("weekly_results", [])
           if w["n_picks"] > 0 and w["success_rate"] is not None and w["success_rate"] < 70]
    if bad:
        print(f"\n  Weeks below 70%:")
        for w in sorted(bad, key=lambda x: x["success_rate"] or 100):
            print(f"    {w['date']}: {w['n_picks']} picks, {w['n_success']} ok ({w['success_rate']:.0f}%)")


