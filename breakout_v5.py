def run_backtest(ohlcv, start_date=None, end_date=None, interval_days=7,
                 verbose=False, use_llm=False):
    """Backtest the scanner across historical dates at weekly intervals."""
    all_dates = sorted({d for df in ohlcv.values() for d in df.index.date})
    if not all_dates: return {"error": "no_dates"}
    if start_date is None:
        start_date = all_dates[min(P.MIN_HISTORY_DAYS + 30, len(all_dates)-1)]
    if end_date is None:
        end_date = all_dates[max(0, len(all_dates) - P.OUTCOME_DAYS - 2)]

    bench_df = find_bench_ticker(ohlcv)
    bench_close = bench_df["Close"] if bench_df is not None else pd.Series(dtype=float)

    test_dates = []
    cur = start_date
    while cur <= end_date:
        nearest = next((d for d in all_dates if d >= cur), None)
        if nearest and nearest <= end_date: test_dates.append(nearest)
        cur += datetime.timedelta(days=interval_days)

    print(f"\n  Backtest: {len(test_dates)} test dates from {start_date} to {end_date}")

    all_picks = []; weekly_results = []
    for i, td in enumerate(test_dates):
        sliced = slice_data(ohlcv, td)
        if not sliced: continue

        bc = bench_close[bench_close.index.date <= td] if not bench_close.empty else pd.Series(dtype=float)
        ratings = compute_rs_ratings(sliced, bc) if len(bc) > 60 else {}
        if not ratings:
            perfs = {tk: float(d["Close"].iloc[-1]/d["Close"].iloc[-min(60,len(d))]-1)
                     for tk, d in sliced.items() if len(d) >= 60}
            if perfs:
                vs = sorted(perfs.values()); n = len(vs)
                ratings = {tk: round(np.searchsorted(vs, p, side='right')/n*100, 1)
                           for tk, p in perfs.items()}

        bench_slice = bench_df[bench_df.index.date <= td] if bench_df is not None else pd.DataFrame()
        picks, funnel = run_scan(sliced, bench_slice, ratings, use_llm=use_llm)

        n_success = 0
        for pick in picks:
            if pick["ticker"] not in ohlcv: continue
            outcome = get_outcome(ohlcv[pick["ticker"]], td, pick["resistance"])
            all_picks.append({"test_date": td, **pick, **outcome})
            if outcome["success"]: n_success += 1

        sr = (n_success/len(picks)*100) if picks else None
        weekly_results.append({"date": td, "n_picks": len(picks),
                               "n_success": n_success, "success_rate": sr})
        if verbose or (i+1) % 10 == 0:
            s = f"{sr:.0f}%" if sr is not None else "N/A"
            print(f"    [{i+1}/{len(test_dates)}] {td}: {len(picks)} picks, {n_success} ok, SR={s}")

    total = len(all_picks)
    success = sum(1 for p in all_picks if p.get("success"))
    overall_sr = success/total*100 if total else 0
    weeks_wp = [w for w in weekly_results if w["n_picks"] > 0]
    wsrs = [w["success_rate"] for w in weeks_wp if w["success_rate"] is not None]
    avg_wsr = np.mean(wsrs) if wsrs else 0
    avg_gain = np.mean([p["max_gain_pct"] for p in all_picks]) if all_picks else 0
    avg_dd = np.mean([p["max_drawdown_pct"] for p in all_picks]) if all_picks else 0

    return {"total_picks": total, "total_success": success,
            "overall_success_rate": round(overall_sr, 1),
            "avg_weekly_success_rate": round(avg_wsr, 1),
            "n_test_dates": len(test_dates), "n_weeks_with_picks": len(weeks_wp),
            "avg_picks_per_week": round(total/max(1, len(weeks_wp)), 1),
            "avg_max_gain_pct": round(avg_gain, 2),
            "avg_max_drawdown_pct": round(avg_dd, 2),
            "all_picks": all_picks, "weekly_results": weekly_results}


