def load_all_cached_ohlcv() -> Dict[str, pd.DataFrame]:
    """Load ALL cached OHLCV data from disk. Returns {ticker: DataFrame}."""
    data = {}
    if not os.path.isdir(CACHE_DIR):
        print(f"  ERROR: Cache directory {CACHE_DIR} not found")
        return data
    files = [f for f in os.listdir(CACHE_DIR) if f.endswith('__1d.csv.gz')]
    print(f"  Loading {len(files)} cached OHLCV files...")
    for fname in files:
        try:
            parts = fname.replace('__1d.csv.gz', '').rsplit('_', 1)
            if len(parts) != 2: continue
            ticker = parts[0]
            if not (ticker.endswith('.NS') or ticker.endswith('.BO')): continue
            filepath = os.path.join(CACHE_DIR, fname)
            with gzip.open(filepath, 'rt') as f:
                header = f.readline()
                if not header.startswith('# ohlcv_cache'):
                    f.seek(0)
                df = pd.read_csv(f, parse_dates=['Date'], index_col='Date')
            if df.empty or len(df) < 30: continue
            required = ['Open', 'High', 'Low', 'Close', 'Volume']
            if not all(c in df.columns for c in required): continue
            df = df[required].dropna()
            df = df[df['Volume'] > 0]
            df = df[df['High'] >= df['Low']]
            df = df.sort_index()
            df = df[~df.index.duplicated(keep='last')]
            if len(df) >= 30:
                data[ticker] = df
        except Exception:
            continue
    print(f"  Loaded {len(data)} tickers with valid data")
    return data


def slice_data(ohlcv, as_of_date):
    """Slice all OHLCV data up to a given date for backtesting."""
    ts = pd.Timestamp(as_of_date)
    return {tk: df[df.index <= ts] for tk, df in ohlcv.items()
            if len(df[df.index <= ts]) >= P.MIN_HISTORY_DAYS}


def get_outcome(df, scan_date, R):
    """Check if price broke above R within OUTCOME_DAYS after scan_date."""
    ts = pd.Timestamp(scan_date)
    future = df[df.index > ts].head(P.OUTCOME_DAYS)
    if future.empty:
        return {"success": False, "max_gain_pct": 0, "days_to_breakout": 0,
                "max_drawdown_pct": 0}
    scan_close = float(df[df.index <= ts].iloc[-1]["Close"])
    target = R * (1 + P.BREAKOUT_THRESHOLD)
    max_high = float(future["High"].max())
    min_low = float(future["Low"].min())
    max_gain = (max_high - scan_close) / scan_close * 100
    max_dd = (scan_close - min_low) / scan_close * 100
    days_to_bo = 0
    for i, (_, row) in enumerate(future.iterrows(), 1):
        if float(row["High"]) >= target:
            days_to_bo = i; break
    return {"success": bool(max_high >= target), "max_gain_pct": round(max_gain, 2),
            "days_to_breakout": days_to_bo, "max_drawdown_pct": round(max_dd, 2)}


