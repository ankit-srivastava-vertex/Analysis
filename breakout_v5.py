def ema(s, p):
    """Exponential moving average."""
    return s.ewm(span=p, adjust=False).mean()


def sma(s, p):
    """Simple moving average."""
    return s.rolling(p).mean()


def atr(df, n=14):
    """Average true range over n periods."""
    h, l, c = df["High"], df["Low"], df["Close"]
    pc = c.shift(1)
    tr = pd.concat([(h-l), (h-pc).abs(), (l-pc).abs()], axis=1).max(axis=1)
    return tr.rolling(n).mean()

def rsi(s, p=14):
    """Relative Strength Index."""
    d = s.diff()
    g = d.where(d>0, 0.0)
    lo = (-d).where(d<0, 0.0)
    ag = g.ewm(alpha=1/p, min_periods=p, adjust=False).mean()
    al = lo.ewm(alpha=1/p, min_periods=p, adjust=False).mean()
    rs = ag / al.replace(0, np.nan)
    return 100 - (100 / (1+rs))

def adx(df, p=14):
    """Average Directional Index."""
    h, l, c = df["High"], df["Low"], df["Close"]
    pdm = h.diff().clip(lower=0)
    mdm = (-l.diff()).clip(lower=0)
    pdm = pdm.where(pdm > mdm, 0)
    mdm = mdm.where(mdm > pdm, 0)
    tr = pd.concat([(h-l), (h-c.shift(1)).abs(), (l-c.shift(1)).abs()], axis=1).max(axis=1)
    atr_s = tr.ewm(alpha=1/p, min_periods=p, adjust=False).mean()
    pdi = 100*(pdm.ewm(alpha=1/p, min_periods=p, adjust=False).mean()/atr_s)
    mdi = 100*(mdm.ewm(alpha=1/p, min_periods=p, adjust=False).mean()/atr_s)
    dx = 100*((pdi-mdi).abs()/(pdi+mdi).replace(0, np.nan))
    return dx.ewm(alpha=1/p, min_periods=p, adjust=False).mean()

def obv(df):
    """On-Balance Volume."""
    sign = np.sign(df["Close"].diff().fillna(0))
    return (sign * df["Volume"]).cumsum()

def bollinger_bands(df, p=20, std=2.0):
    """Bollinger Bands: upper, middle, lower."""
    mid = sma(df["Close"], p)
    s = df["Close"].rolling(p).std()
    return mid + std*s, mid, mid - std*s

def keltner_channels(df, p=20, mult=1.5):
    """Keltner Channels: upper, middle, lower."""
    mid = ema(df["Close"], p)
    a = atr(df, p)
    return mid + mult*a, mid, mid - mult*a

def linreg_slope(y):
    """Linear regression slope of a series."""
    v = y.dropna().values
    if len(v) < 5: return 0.0
    return float(np.polyfit(np.arange(len(v)), v, 1)[0])

def fractal_pivots(highs, k=3):
    """Identify fractal pivot highs (local maxima with k bars on each side)."""
    mask = pd.Series(False, index=highs.index)
    v = highs.values; n = len(v)
    for i in range(k, n-k):
        w = v[max(0, i-k):i+k+1]
        if v[i] == w.max() and np.sum(w == v[i]) == 1:
            mask.iloc[i] = True
    return mask

def resample_weekly(df):
    """Resample daily OHLCV to weekly (Friday close)."""
    return df.resample('W-FRI').agg({
        'Open':'first', 'High':'max', 'Low':'min', 'Close':'last', 'Volume':'sum'
    }).dropna()


