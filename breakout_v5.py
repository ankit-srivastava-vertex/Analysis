def llm_market_regime(bench_df, sector_stage_data=None):
    """Assess market regime and recommend dynamic threshold adjustments.

    Called once at the top of run_scan() before any stock-level processing.
    Returns a dict with regime classification and parameter overrides, or None
    if LLM is unavailable.
    """
    if not _USE_LLM or llm_json is None or not llm_is_available():
        return None
    if bench_df is None or bench_df.empty or len(bench_df) < 60:
        return None

    c = bench_df["Close"].tail(60)
    last = float(c.iloc[-1])
    returns = c.pct_change().dropna()
    m5 = float(c.tail(5).mean())
    m20 = float(c.tail(20).mean())
    m50 = float(c.mean())
    atr_vals = (bench_df["High"] - bench_df["Low"]).tail(20)
    avg_atr = float(atr_vals.mean())
    atr_pct = round(avg_atr / last * 100, 2) if last > 0 else 0

    bench_summary = {
        "last_close": round(last, 2),
        "5d_avg": round(m5, 2),
        "20d_avg": round(m20, 2),
        "50d_avg": round(m50, 2),
        "above_20dma": last > m20,
        "above_50dma": last > m50,
        "20d_return_pct": round(float(returns.tail(20).sum() * 100), 2),
        "5d_return_pct": round(float(returns.tail(5).sum() * 100), 2),
        "avg_daily_range_pct": atr_pct,
        "max_drawdown_20d_pct": round(
            float((c.tail(20).max() - c.tail(20).min()) / c.tail(20).max() * 100), 2),
    }

    sector_summary = ""
    if sector_stage_data:
        sector_summary = json.dumps(sector_stage_data, default=str)

    system_prompt = (
        "You are a quantitative market regime analyst for Indian equities. "
        "Assess whether the current market environment is receptive to "
        "breakout strategies. You MUST respond with valid JSON only."
    )

    user_prompt = (
        "Nifty 50 benchmark (last 60 days summary):\n"
        f"{json.dumps(bench_summary, indent=1)}\n\n"
    )
    if sector_summary:
        user_prompt += f"Sector stage data:\n{sector_summary}\n\n"
    user_prompt += (
        "Evaluate breakout receptiveness. Consider:\n"
        "1. Is the market trending up (above MAs) or down?\n"
        "2. Is volatility expanding (hostile to breakouts) or contracting?\n"
        "3. How many sectors are in Stage 2 (advancing) vs Stage 3/4 (topping/declining)?\n"
        "4. Is this a broad advance or narrow/rotational?\n\n"
        "Return JSON:\n"
        '{"regime": "strong_bull | bull | neutral | cautious | hostile",\n'
        ' "breakout_receptiveness": 0-100,\n'
        ' "dynamic_adjustments": {\n'
        '   "min_score_override": 45-75 (raise in weak markets),\n'
        '   "proximity_max_override": 0.01-0.03 (tighten in cautious markets),\n'
        '   "require_squeeze": true/false (require squeeze in cautious+ markets)\n'
        ' },\n'
        ' "rationale": "1-2 sentences"}'
    )

    try:
        result = llm_json(system_prompt, user_prompt, max_tokens=1000, timeout=60)
    except Exception as e:
        print(f"  [regime] LLM failed: {e}")
        return None

    if not result or "regime" not in result:
        return None

    print(f"  [regime] {result.get('regime', 'unknown').upper()} "
          f"(receptiveness: {result.get('breakout_receptiveness', '?')}/100) "
          f"— {result.get('rationale', '')}")
    return result


def llm_conviction_court(picks, ohlcv, regime):
    """Final LLM filter: reviews each pick for base quality, risk, and kill signals.

    Called after scoring and risk_plan(), before the MAX_PICKS cap.
    Returns a filtered list of picks (rejected picks are dropped).
    """
    if not _USE_LLM or llm_json is None or not llm_is_available():
        return picks
    if not picks:
        return picks

    pick_summaries = []
    for p in picks[:20]:
        tk = p["ticker"]
        df = ohlcv.get(tk)
        summary = {
            "ticker": tk,
            "score": p["score"],
            "close": p["close"],
            "resistance": p["resistance"],
            "distance_pct": p["distance_pct"],
            "rs_rating": p["rs_rating"],
            "touches": p["touches"],
            "base_days": p["base_days"],
            "base_range": round(p.get("base_range", 0) * 100, 1),
            "higher_lows": p.get("higher_lows", False),
            "n_vcp": p.get("n_vcp", 0),
            "squeeze_type": p.get("squeeze_type", ""),
            "institutional": p.get("institutional", ""),
            "weekly_rsi": p.get("weekly_rsi", 0),
            "rr": p.get("rr", 0),
            "risk_pct": p.get("risk_pct", 0),
            "reward_pct": p.get("reward_pct", 0),
            "stop": p.get("stop", 0),
            "target": p.get("target", 0),
        }

        if df is not None and len(df) >= 10:
            last10 = df.tail(10)
            vol_50d = float(df["Volume"].tail(50).mean()) if len(df) >= 50 else 1
            summary["last_10_bars"] = [
                {"O": round(float(r["Open"]), 2), "H": round(float(r["High"]), 2),
                 "L": round(float(r["Low"]), 2), "C": round(float(r["Close"]), 2),
                 "V_ratio": round(float(r["Volume"]) / vol_50d, 2) if vol_50d > 0 else 0}
                for _, r in last10.iterrows()
            ]
            if len(df) >= 50:
                summary["vol_trend"] = ("rising" if float(df["Volume"].tail(10).mean()) >
                                        float(df["Volume"].tail(50).mean()) * 1.1
                                        else "flat_or_declining")
                rs_10d = df["Close"].tail(10)
                summary["rs_10d_change"] = round(
                    float((rs_10d.iloc[-1] / rs_10d.iloc[0] - 1) * 100), 2)

        pick_summaries.append(summary)

    regime_note = ""
    if regime:
        regime_note = (f"\nMarket regime: {regime.get('regime', 'unknown')} "
                       f"(receptiveness: {regime.get('breakout_receptiveness', '?')}/100)")

    system_prompt = (
        "You are the final conviction filter for a breakout scanner targeting "
        "95%+ success rate on Indian stocks. Your job is to find reasons to "
        "REJECT — be paranoid. A false positive costs more than a missed "
        "opportunity. You MUST respond with valid JSON only."
    )

    user_prompt = (
        f"Review these {len(pick_summaries)} breakout candidates.{regime_note}\n\n"
        "For each pick, evaluate:\n"
        "1. BASE QUALITY: Clean orderly consolidation vs choppy/messy? "
        "Volume drying up? Touches at R clean or wicky?\n"
        "2. RISK PROFILE: Is R:R >= 1.0? Stop reasonable (< 8% from entry)?\n"
        "3. TIMING: Approaching R at right speed? Too fast = chasing. "
        "Too slow = no catalyst.\n"
        "4. KILL SIGNALS: Distribution signs? Expanding range at R? "
        "Declining RS in last 10 days? Very high weekly RSI (>75 = overbought)?\n"
        "5. REGIME FIT: Does this setup match market conditions?\n\n"
        "Candidates:\n"
        + json.dumps(pick_summaries, indent=1, default=str)
        + "\n\nReturn JSON:\n"
        '{"verdicts": [{"ticker": "X.NS", "verdict": "APPROVE" or "REJECT", '
        '"conviction": 0-100, "base_quality": 0-10, '
        '"risk_assessment": "acceptable | marginal | poor", '
        '"concerns": ["list"], "thesis": "1 sentence"}]}'
    )

    try:
        result = llm_json(system_prompt, user_prompt, max_tokens=4000, timeout=120)
    except Exception as e:
        print(f"  [court] LLM conviction court failed: {e}")
        return picks

    if not result or "verdicts" not in result:
        return picks

    verdict_map = {}
    for v in result["verdicts"]:
        tk = v.get("ticker", "")
        verdict_map[tk] = v

    approved = []
    rejected_count = 0
    for p in picks:
        v = verdict_map.get(p["ticker"])
        if v and v.get("verdict") == "REJECT":
            rejected_count += 1
            continue
        if v:
            p["llm_conviction"] = v.get("conviction", 50)
            p["llm_base_quality"] = v.get("base_quality", 5)
            p["llm_thesis"] = v.get("thesis", "")
            p["llm_concerns"] = v.get("concerns", [])
        approved.append(p)

    if rejected_count:
        print(f"  [court] Conviction court: {rejected_count} rejected, "
              f"{len(approved)} approved")
    return approved


