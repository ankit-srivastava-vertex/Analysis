def run_live_scan(verbose=False, use_llm=True):
    """Run a live scan on cached data and output to console + Excel."""
    global _USE_LLM
    _USE_LLM = use_llm

    print("\n  Breakout V5.1 — Adaptive Conviction Engine")
    print("  " + "="*50)
    ohlcv = load_all_cached_ohlcv()
    if not ohlcv:
        print("  ERROR: No cached data."); return []

    bench_df = find_bench_ticker(ohlcv)
    bench_close = bench_df["Close"] if bench_df is not None else pd.Series(dtype=float)

    print("  Computing RS ratings...")
    ratings = compute_rs_ratings(ohlcv, bench_close)

    print("  Running scan (3 hard gates + score boosters + LLM intelligence)...")
    picks, funnel = run_scan(ohlcv, bench_df if bench_df is not None else pd.DataFrame(),
                             ratings, verbose=verbose, use_llm=use_llm)

    print(f"\n  FUNNEL:")
    for k, v in sorted(funnel.items()):
        print(f"    {k}: {v}")

    if not picks:
        print("\n  ⚠️  No stocks met minimum conviction score.")
        write_excel([], funnel); return []

    print(f"\n  {'='*70}")
    print(f"  BREAKOUT CANDIDATES ({len(picks)} stocks, min score={P.MIN_SCORE})")
    print(f"  {'='*70}")
    for i, p in enumerate(picks[:20], 1):
        risk_flag = " ⚠️ WEAK MKT" if p.get("market_boost", 0) < 5 else ""
        print(f"\n  #{i} {p['ticker']} — Score: {p['score']}/100{risk_flag}")
        print(f"     Close: ₹{p['close']}  |  R: ₹{p['resistance']}  |  Dist: {p['distance_pct']:.1f}%")
        print(f"     RS: {p['rs_rating']:.0f}  |  Touches: {p['touches']}  |  Base: {p['base_days']}d")
        print(f"     Squeeze: {p['squeeze_type'] or 'none'}  |  Inst: {p['institutional']}")
        print(f"     Entry: ₹{p['entry']}  Stop: ₹{p['stop']}  Target: ₹{p['target']}  R:R={p['rr']}")

    write_excel(picks, funnel)
    return picks


