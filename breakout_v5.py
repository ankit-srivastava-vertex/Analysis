def booster_market_regime(bench):
    """B0: Market health. Returns 0-15 score."""
    if bench is None or len(bench) < 60: return 0, {}
    c = bench["Close"]; last = float(c.iloc[-1])
    above_ema = last > float(ema(c, P.MARKET_EMA_PERIOD).iloc[-1])
    above_sma = last > float(sma(c, P.MARKET_SMA_PERIOD).iloc[-1])
    adx_val = float(adx(bench, P.MARKET_ADX_PERIOD).iloc[-1])
    score = sum([above_ema, above_sma, adx_val > 20])
    return round(P.W_MARKET * score/3, 1), {
        "above_ema": above_ema, "above_sma": above_sma, "adx": round(adx_val, 1)}


def booster_squeeze(df):
    """B4: Volatility compression. Returns 0-15 score."""
    if len(df) < 60: return 0, []
    types = []
    bbu, _, bbl = bollinger_bands(df, P.BB_PERIOD, P.BB_STD)
    kcu, _, kcl = keltner_channels(df, P.KC_PERIOD, P.KC_ATR_MULT)
    sq = sum(1 for i in range(-5, 0)
             if (not pd.isna(bbu.iloc[i]) and not pd.isna(kcu.iloc[i])
                 and float(bbu.iloc[i]) < float(kcu.iloc[i])
                 and float(bbl.iloc[i]) > float(kcl.iloc[i])))
    if sq >= P.SQUEEZE_MIN_BARS: types.append("bb_kc")

    a = atr(df)
    if len(a) >= 50:
        now = float(a.iloc[-10:].mean())
        then = float(a.iloc[-50:-30].mean())
        if then > 0 and now/then < P.ATR_COMPRESSION_RATIO: types.append("atr_comp")

    rr = float(df["High"].tail(10).max() - df["Low"].tail(10).min())
    br = float(df["High"].tail(50).max() - df["Low"].tail(50).min())
    if br > 0 and rr/br < 0.40: types.append("narrow_range")

    score = P.W_SQUEEZE * min(len(types)/2, 1.0)
    return round(score, 1), types


def booster_weekly(df, R):
    """B6: Weekly timeframe confirmation. Returns 0-10 score."""
    w = resample_weekly(df)
    if len(w) < 12: return 0, {}
    wc = w["Close"]; last = float(wc.iloc[-1])
    wma_val = sma(wc, P.WEEKLY_MA_PERIOD)
    if pd.isna(wma_val.iloc[-1]): return 0, {}
    above_wma = last > float(wma_val.iloc[-1])

    rh = float(wc.tail(26).max())
    pct_off = (rh - last)/rh if rh > 0 else 1
    near_high = pct_off <= P.WEEKLY_NEAR_HIGH_PCT

    wrsi = rsi(wc, P.WEEKLY_RSI_PERIOD)
    wrsi_val = float(wrsi.iloc[-1]) if not pd.isna(wrsi.iloc[-1]) else 50
    rsi_ok = P.WEEKLY_RSI_MIN <= wrsi_val <= P.WEEKLY_RSI_MAX

    checks = sum([above_wma, near_high, rsi_ok])
    score = P.W_WEEKLY * checks/3
    return round(score, 1), {"above_wma": above_wma, "near_high": near_high,
                              "weekly_rsi": round(wrsi_val, 1), "rsi_ok": rsi_ok}


